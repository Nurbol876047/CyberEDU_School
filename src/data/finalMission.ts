export function parseMission(text: string): Mission | null {
  try {
    const cleaned = text.replace(/```json|```/g, "").trim();
    const m = JSON.parse(cleaned) as Mission;
    if (!m.title || !Array.isArray(m.steps) || m.steps.length < 4) return null;
    for (const s of m.steps) {
      if (!s.situation || !Array.isArray(s.options) || s.options.length < 2) return null;
      if (!s.options.some((o) => o.correct)) return null;
    }
    return { ...m, intro: m.intro ?? "", outro: m.outro ?? "Миссия выполнена!" };
  } catch {
    return null;
  }
}

